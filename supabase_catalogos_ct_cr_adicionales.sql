-- Catalogos adicionales de Centros de Trabajo y Centros de Recurso.
-- Generado desde la tabla compartida por el usuario.

create table if not exists public."CT_CentrosTrabajo" (
  id bigserial primary key,
  "Actividad" text not null,
  "CT" text not null unique,
  "Descripcion" text not null,
  created_at timestamptz not null default now()
);

create table if not exists public."CR_CentrosRecurso" (
  id bigserial primary key,
  "CT" text not null references public."CT_CentrosTrabajo"("CT") on update cascade on delete restrict,
  "CR" text not null unique,
  "Descripcion" text not null,
  "Costo_Hr" numeric(18,4),
  created_at timestamptz not null default now()
);

alter table public."CT_CentrosTrabajo" enable row level security;
alter table public."CR_CentrosRecurso" enable row level security;

drop policy if exists "Permitir todo CT" on public."CT_CentrosTrabajo";
drop policy if exists "Permitir todo CR" on public."CR_CentrosRecurso";

create policy "Permitir todo CT"
on public."CT_CentrosTrabajo"
for all
to anon
using (true)
with check (true);

create policy "Permitir todo CR"
on public."CR_CentrosRecurso"
for all
to anon
using (true)
with check (true);

